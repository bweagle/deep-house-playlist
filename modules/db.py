"""
SQLite database schema and helpers for the Deep House pipeline.

All pipeline state lives in a single deephouse.db file so every module
can share data without file-passing gymnastics.
"""

import sqlite3
from pathlib import Path

_DEFAULT_DB = Path("deephouse.db")


def get_connection(db_path: str | Path = _DEFAULT_DB) -> sqlite3.Connection:
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def init_db(db_path: str | Path = _DEFAULT_DB) -> None:
    """Create all tables if they don't exist. Safe to call repeatedly."""
    conn = get_connection(db_path)
    conn.executescript("""
        -- Source catalog loaded from songs.csv
        CREATE TABLE IF NOT EXISTS catalog (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            title           TEXT    NOT NULL,
            artist          TEXT    NOT NULL,
            bpm             REAL,
            key_camelot     TEXT,
            duration        TEXT,
            rating          TEXT,
            notes           TEXT,
            local           TEXT,
            spotify_id      TEXT    UNIQUE,
            fetched_at      TEXT
        );

        -- Spotify audio features (may be empty if API is deprecated)
        CREATE TABLE IF NOT EXISTS audio_features (
            spotify_id          TEXT PRIMARY KEY,
            danceability        REAL,
            energy              REAL,
            valence             REAL,
            tempo               REAL,
            loudness            REAL,
            acousticness        REAL,
            instrumentalness    REAL,
            speechiness         REAL,
            spotify_key         INTEGER,
            mode                INTEGER,
            time_signature      INTEGER,
            fetched_at          TEXT
        );

        -- Computed taste profile — singleton row (id always 1)
        CREATE TABLE IF NOT EXISTS taste_profile (
            id                  INTEGER PRIMARY KEY CHECK (id = 1),
            avg_bpm             REAL,
            avg_energy          REAL,
            avg_danceability    REAL,
            avg_valence         REAL,
            avg_acousticness    REAL,
            avg_instrumentalness REAL,
            top_keys            TEXT,
            computed_at         TEXT
        );

        -- Recommendations generated by each pipeline run
        CREATE TABLE IF NOT EXISTS recommendations (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            run_id      TEXT    NOT NULL,
            source      TEXT    NOT NULL,
            title       TEXT    NOT NULL,
            artist      TEXT    NOT NULL,
            spotify_id  TEXT,
            reason      TEXT,
            score       REAL,
            rank        INTEGER,
            created_at  TEXT
        );

        -- Published weekly playlists
        CREATE TABLE IF NOT EXISTS weekly_mixes (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            run_id          TEXT    NOT NULL UNIQUE,
            playlist_id     TEXT,
            playlist_name   TEXT,
            track_count     INTEGER,
            published_at    TEXT,
            created_at      TEXT
        );

        -- Individual tracks in each published mix
        CREATE TABLE IF NOT EXISTS mix_tracks (
            id               INTEGER PRIMARY KEY AUTOINCREMENT,
            run_id           TEXT    NOT NULL REFERENCES weekly_mixes(run_id),
            position         INTEGER NOT NULL,
            title            TEXT    NOT NULL,
            artist           TEXT,
            spotify_id       TEXT,
            youtube_video_id TEXT,
            camelot_key      TEXT,
            bpm              REAL
        );

        -- Pipeline run log
        CREATE TABLE IF NOT EXISTS run_log (
            run_id          TEXT PRIMARY KEY,
            started_at      TEXT,
            completed_at    TEXT,
            status          TEXT,
            tracks_generated INTEGER,
            tracks_published INTEGER,
            errors          TEXT
        );
    """)
    conn.commit()
    conn.close()
