"""
SQLite database schema and helpers for the Deep House pipeline.

All pipeline state lives in a single deephouse.db file so every module
can share data without file-passing gymnastics.
"""

import sqlite3
from pathlib import Path

_DEFAULT_DB = Path("deephouse.db")


def get_connection(db_path: str | Path = _DEFAULT_DB) -> sqlite3.Connection:
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def init_db(db_path: str | Path = _DEFAULT_DB) -> None:
    """Create all tables if they don't exist. Safe to call repeatedly."""
    conn = get_connection(db_path)
    conn.executescript("""
        -- Source catalog loaded from songs.csv
        CREATE TABLE IF NOT EXISTS catalog (
            id                  INTEGER PRIMARY KEY AUTOINCREMENT,
            title               TEXT    NOT NULL,
            artist              TEXT    NOT NULL,
            bpm                 REAL,
            key_camelot         TEXT,
            duration            TEXT,
            rating              TEXT,
            notes               TEXT,
            local               TEXT,
            beatport_id         INTEGER UNIQUE,
            beatport_artist_ids TEXT,   -- JSON array of artist IDs
            genre               TEXT,
            sub_genre           TEXT,
            label               TEXT,
            release_date        TEXT,
            fetched_at          TEXT
        );

        -- Computed taste profile — singleton row (id always 1)
        CREATE TABLE IF NOT EXISTS taste_profile (
            id              INTEGER PRIMARY KEY CHECK (id = 1),
            avg_bpm         REAL,
            bpm_std         REAL,
            top_keys        TEXT,   -- JSON array of Camelot keys
            genre_weights   TEXT,   -- JSON object: {genre: weight}
            top_labels      TEXT,   -- JSON array of label names
            top_artists     TEXT,   -- JSON array of artist names
            computed_at     TEXT
        );

        -- Recommendations generated by each pipeline run
        CREATE TABLE IF NOT EXISTS recommendations (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            run_id          TEXT    NOT NULL,
            source          TEXT    NOT NULL,
            title           TEXT    NOT NULL,
            artist          TEXT    NOT NULL,
            spotify_id      TEXT,
            beatport_id     INTEGER,
            bpm             REAL,
            camelot_key     TEXT,
            genre           TEXT,
            sub_genre       TEXT,
            label           TEXT,
            release_date    TEXT,
            reason          TEXT,
            score           REAL,
            rank            INTEGER,
            duration_ms     INTEGER,
            created_at      TEXT
        );

        -- Published weekly playlists
        CREATE TABLE IF NOT EXISTS weekly_mixes (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            run_id          TEXT    NOT NULL UNIQUE,
            playlist_id     TEXT,
            playlist_name   TEXT,
            track_count     INTEGER,
            published_at    TEXT,
            created_at      TEXT
        );

        -- Individual tracks in each published mix
        CREATE TABLE IF NOT EXISTS mix_tracks (
            id               INTEGER PRIMARY KEY AUTOINCREMENT,
            run_id           TEXT    NOT NULL REFERENCES weekly_mixes(run_id),
            position         INTEGER NOT NULL,
            title            TEXT    NOT NULL,
            artist           TEXT,
            beatport_id      INTEGER,
            youtube_video_id TEXT,
            camelot_key      TEXT,
            bpm              REAL,
            genre            TEXT,
            label            TEXT
        );

        -- Pipeline run log
        CREATE TABLE IF NOT EXISTS run_log (
            run_id          TEXT PRIMARY KEY,
            started_at      TEXT,
            completed_at    TEXT,
            status          TEXT,
            tracks_generated INTEGER,
            tracks_published INTEGER,
            errors          TEXT
        );
    """)
    conn.commit()

    # Migrations — add columns introduced after initial schema
    _migrate(conn)
    conn.close()


def _migrate(conn: sqlite3.Connection) -> None:
    existing = {r[1] for r in conn.execute("PRAGMA table_info(recommendations)").fetchall()}
    if "duration_ms" not in existing:
        conn.execute("ALTER TABLE recommendations ADD COLUMN duration_ms INTEGER")

    catalog_cols = {r[1] for r in conn.execute("PRAGMA table_info(catalog)").fetchall()}
    if "beatport_searched_at" not in catalog_cols:
        conn.execute("ALTER TABLE catalog ADD COLUMN beatport_searched_at TEXT")
    if "youtube_video_id" not in catalog_cols:
        conn.execute("ALTER TABLE catalog ADD COLUMN youtube_video_id TEXT")
    if "youtube_searched_at" not in catalog_cols:
        conn.execute("ALTER TABLE catalog ADD COLUMN youtube_searched_at TEXT")

    # Deduplicate catalog rows (can accumulate if analyze is run multiple times)
    # Keep the first (lowest id) row per title+artist, then enforce uniqueness.
    indexes = {r[1] for r in conn.execute("PRAGMA index_list(catalog)").fetchall()}
    if "catalog_title_artist" not in indexes:
        conn.execute("""
            DELETE FROM catalog WHERE id NOT IN (
                SELECT MIN(id) FROM catalog GROUP BY title, artist
            )
        """)
        conn.execute("CREATE UNIQUE INDEX catalog_title_artist ON catalog(title, artist)")

    conn.commit()
